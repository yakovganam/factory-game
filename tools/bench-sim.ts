/**
 * Simulation scaling benchmark (CPU only, Node). Clones a running two-line level-1 workshop into
 * N production sites (each with its own van) and measures the authoritative tick cost.
 * Run: npx tsx tools/bench-sim.ts
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { buildDB } from '../src/content/db';
import { ch1 } from '../src/content/data/ch1_workshop';
import { newGame, Sim } from '../src/sim/game';
import { applyDemoLayout } from '../src/sim/demo';
import { TPS } from '../src/sim/types';

const db = buildDB([ch1]);
function makeCity(n: number): Sim {
  const sim = new Sim(db, newGame(db, 99));
  applyDemoLayout(sim);
  const s = sim.s;
  s.tutorial.skipped = true;
  s.cash = 1e12;
  s.workforce = 100000;
  const base = s.factories.ws1;
  const bws = s.buildings.find((b) => b.id === 'ws1')!;
  for (let i = 2; i <= n; i++) {
    const id = `ws${i}`;
    s.buildings.push({ ...bws, id });
    const f = JSON.parse(JSON.stringify(base));
    f.id = id;
    s.factories[id] = f;
    s.vehicles.push({ ...JSON.parse(JSON.stringify(s.vehicles[0])), id: s.nextId++, home: id });
  }
  return sim;
}
const rows: string[] = [];
for (const n of [1, 10, 50, 100, 200]) {
  const sim = makeCity(n);
  // Keep every site supplied (direct stock injection so the benchmark measures steady-state work).
  const feed = () => { for (const f of Object.values(sim.s.factories)) { f.inbound.wood_pieces = 100; f.inbound.carton_flat = 100; } };
  feed();
  sim.run(TPS * 30); // warm up
  const ticks = TPS * 60;
  const t0 = performance.now();
  for (let i = 0; i < ticks; i++) {
    if (i % 100 === 0) feed();
    sim.step();
    sim.ev.drain();
  }
  const ms = performance.now() - t0;
  const ents = Object.values(sim.s.factories).reduce((a, f) => a + f.entities.length, 0);
  const perTick = ms / ticks;
  const line = `| ${n} | ${ents} | ${perTick.toFixed(3)} ms | ${((perTick * TPS) / 1000 * 100).toFixed(2)}% of one core at 1× | ${(perTick * TPS * 3 / 1000 * 100).toFixed(2)}% at 3× | ${(14400 * TPS * perTick / 1000).toFixed(1)} s |`;
  rows.push(line);
  console.log(line);
}
const md = `# Simulation scaling benchmark (CPU, Node ${process.version})\n\nGenerated by \`npx tsx tools/bench-sim.ts\` on ${new Date().toISOString().slice(0, 10)}. Machine: ${(await import('node:os')).cpus()[0].model}, ${(await import('node:os')).cpus().length} vCPU.\n\nEach site is a running level-1 workshop with two production lines (16 entities incl. belts) and its own delivery van. This measures only the authoritative simulation — no rendering. Browser JIT on phones is typically 3–8× slower than this desktop-class Node; device measurements are still required.\n\n| Sites | Entities | Tick cost | CPU share (10 Hz, 1×) | CPU share (3×) | 4 h offline catch-up |\n|---|---|---|---|---|---|\n${rows.join('\n')}\n`;
mkdirSync('docs/qa', { recursive: true });
writeFileSync('docs/qa/sim-benchmark.md', md);
