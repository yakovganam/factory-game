#!/usr/bin/env node
// Renders every SFX catalog event (all variations) offline in headless Chromium and writes
// docs/qa/audio-sfx-report.md. Fails (exit 1) on silence, clipping, bad loop seams, missing
// required ids or near-duplicate variations.
//   node tools/audio/check-sfx.mjs [--wav]   (--wav also dumps WAVs to tools/audio/out/sfx/)
import fs from 'node:fs';
import path from 'node:path';
import { openPage, fetchBlob, ROOT } from './lib/harness.mjs';

const dumpWav = process.argv.includes('--wav');
const t0 = Date.now();
const { browser, page, errors } = await openPage('tools/audio/sfx-entry.ts');
const list = await page.evaluate(() => window.__sfx.list());
const required = await page.evaluate(() => window.__sfx.required());

const failures = [];
const warnings = [];
const ids = new Set(list.map((d) => d.id));
for (const id of required) if (!ids.has(id)) failures.push(`missing required event ${id}`);
for (const d of list) {
  if (d.id.startsWith('loop_') !== d.loop) failures.push(`${d.id}: loop flag must match the loop_ prefix`);
}

const rows = [];
let totalSamples = 0;
for (const d of list) {
  const per = [];
  for (let v = 0; v < d.variations; v++) {
    const r = await page.evaluate(([id, vv, keep]) => window.__sfx.render(id, vv, keep), [d.id, v, dumpWav]);
    if (!r) {
      failures.push(`${d.id}#${v}: render failed`);
      continue;
    }
    totalSamples += Math.round(r.stats.durationSec * r.sr) * r.stats.channels;
    const st = r.stats;
    const problems = [];
    if (st.peakDb < -40 || st.rmsDb < -60) problems.push('silent');
    if (st.peakDb > -0.3) problems.push('clipping');
    if (Math.abs(st.dc) > 0.01) problems.push('dc-offset');
    if (!d.loop && st.durationSec > d.duration + (d.tail ?? 0.08) + 0.02) problems.push('overlong');
    if (d.loop) {
      if (Math.abs(st.durationSec - d.duration) > 0.001) problems.push('loop-length');
      if (r.seam.ratio > 1.0) problems.push(`seam-jump x${r.seam.ratio.toFixed(2)}`);
      if (r.seam.edgeDb > 3) problems.push(`seam-level ${r.seam.edgeDb.toFixed(1)}dB`);
      if (st.silentFraction > 0.05) problems.push('loop-has-gaps');
    } else if (st.silentFraction > 0.8) problems.push('mostly-silent');
    for (const p of problems) failures.push(`${d.id}#${v}: ${p}`);
    per.push({ v, r, problems });
    if (dumpWav) {
      const wav = await fetchBlob(page, `${d.id}_${v}`);
      const dir = path.join(ROOT, 'tools/audio/out/sfx');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${d.id}_${v}.wav`), wav);
    }
  }
  // near-duplicate variation check: compare spectral/temporal features pairwise
  for (let a = 0; a < per.length; a++) {
    for (let b = a + 1; b < per.length; b++) {
      const A = per[a].r;
      const B = per[b].r;
      const rel = (x, y) => Math.abs(x - y) / Math.max(1e-6, (Math.abs(x) + Math.abs(y)) / 2);
      const diffs = [
        rel(A.spectral.centroidHz, B.spectral.centroidHz),
        rel(A.stats.durationSec, B.stats.durationSec),
        Math.abs(A.spectral.bands.low - B.spectral.bands.low) * 4,
        Math.abs(A.spectral.bands.mid - B.spectral.bands.mid) * 4,
        Math.abs(A.spectral.bands.high - B.spectral.bands.high) * 4,
        rel(A.spectral.rolloffHz, B.spectral.rolloffHz),
        Math.abs(A.stats.rmsDb - B.stats.rmsDb) / 6,
        rel(A.trajectory[0], B.trajectory[0]),
        rel(A.trajectory[1], B.trajectory[1]),
      ];
      const maxDiff = Math.max(...diffs);
      if (maxDiff < 0.04) failures.push(`${d.id}: variations ${a} and ${b} are near-duplicates (max feature diff ${(maxDiff * 100).toFixed(1)}%)`);
      else if (maxDiff < 0.1) warnings.push(`${d.id}: variations ${a} and ${b} are similar (max feature diff ${(maxDiff * 100).toFixed(1)}%) — intended?`);
    }
  }
  rows.push({ d, per });
}
await browser.close();
for (const e of errors) failures.push(`page error: ${e}`);

// ------------------------------------------------------------------ report
const f1 = (x) => (Number.isFinite(x) ? x.toFixed(1) : '—');
const pct = (x) => `${Math.round(x * 100)}`;
const lines = [];
const nEvents = list.length;
const nVars = rows.reduce((a, r) => a + r.per.length, 0);
const loops = list.filter((d) => d.loop).length;
lines.push('# Audio QA — SFX report');
lines.push('');
lines.push(`Generated by \`node tools/audio/check-sfx.mjs\` on ${new Date().toISOString()} (headless Chromium, OfflineAudioContext at the runtime render rates: one-shots 44.1 kHz, loops 32 kHz, stereo ambience beds 24 kHz).`);
lines.push('');
lines.push(`- Events: **${nEvents}** (${loops} loops, ${nEvents - loops} one-shots), rendered variations: **${nVars}**`);
lines.push(`- Required ids present: ${required.every((id) => ids.has(id)) ? 'yes' : 'NO'} (${required.length} required)`);
lines.push(`- Result: **${failures.length === 0 ? 'PASS' : `FAIL (${failures.length})`}**, warnings: ${warnings.length}`);
lines.push(`- Decoded bank size if fully rendered: ${((totalSamples * 4) / 1048576).toFixed(1)} MB float32 (rendered lazily in priority order; UI first)`);
lines.push(`- Total render time in headless Chromium: ${((Date.now() - t0) / 1000).toFixed(1)} s (includes page start-up)`);
lines.push('');
lines.push('Checks: not silent (peak > -40 dBFS, RMS > -60 dBFS), no clipping (peak <= -0.3 dBFS; renderer caps at -1 dBFS), DC < 1%,');
lines.push('loops: exact loop length, wrap jump |x[0]-x[N-1]| <= 99.9th-percentile sample step, first/last 50 ms RMS within 3 dB, no gaps;');
lines.push('variations: pairwise spectral/temporal feature distance >= 4% (near-duplicates fail, < 10% warns).');
lines.push('');
lines.push('Columns: `peak`/`rms` dBFS of the normalized buffer; `loud` = loudest 100 ms window of K-weighted (+100 Hz small-speaker high-pass) signal, LUFS-like — the normalization measure; `eff` = loud + 20·log10(catalog gain) (relative mix level before bus/spatial gain);');
lines.push('`cent` = spectral centroid; `L/M/H` = % energy in 80–300 Hz / 300–3k / 3k–8k; `seam` = wrap jump ratio and edge level diff (loops).');
lines.push('');
if (failures.length) {
  lines.push('## Failures');
  for (const f of failures) lines.push(`- ${f}`);
  lines.push('');
}
if (warnings.length) {
  lines.push('## Warnings');
  for (const w of warnings) lines.push(`- ${w}`);
  lines.push('');
}
lines.push('## Per event / variation');
lines.push('');
lines.push('| event | bus | var | dur s | peak | rms | loud | eff | cent Hz | L/M/H % | seam | status |');
lines.push('|---|---|---|---|---|---|---|---|---|---|---|---|');
for (const { d, per } of rows) {
  for (const { v, r, problems } of per) {
    const s = r.stats;
    const eff = r.loudness + 20 * Math.log10(d.gain);
    const b = r.spectral.bands;
    const seamTxt = r.seam ? `x${r.seam.ratio.toFixed(2)} / ${r.seam.edgeDb.toFixed(1)} dB` : '';
    lines.push(
      `| ${v === 0 ? `\`${d.id}\`` : ''} | ${v === 0 ? d.bus : ''} | ${v} | ${s.durationSec.toFixed(2)} | ${f1(s.peakDb)} | ${f1(s.rmsDb)} | ${f1(r.loudness)} | ${f1(eff)} | ${Math.round(r.spectral.centroidHz)} | ${pct(b.low)}/${pct(b.mid)}/${pct(b.high)} | ${seamTxt} | ${problems.length ? problems.join(', ') : 'ok'} |`,
    );
  }
}
lines.push('');
lines.push('## Catalog');
lines.push('');
lines.push('| event | category | loop | vars | gain | maxVoices | minInterval s | description |');
lines.push('|---|---|---|---|---|---|---|---|');
for (const d of list) lines.push(`| \`${d.id}\` | ${d.category} | ${d.loop ? 'yes' : ''} | ${d.variations} | ${d.gain} | ${d.maxVoices} | ${d.loop ? '' : d.minInterval} | ${d.description}${d.variationNotes ? ` *(${d.variationNotes})*` : ''} |`);
lines.push('');
const out = path.join(ROOT, 'docs/qa/audio-sfx-report.md');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));
console.log(`SFX: ${nEvents} events, ${nVars} variations, ${failures.length} failures, ${warnings.length} warnings -> ${path.relative(ROOT, out)}`);
for (const f of failures.slice(0, 40)) console.log('  FAIL', f);
for (const w of warnings.slice(0, 40)) console.log('  warn', w);
process.exit(failures.length ? 1 : 0);
