/**
 * Generates content documentation from the catalog:
 *   docs/factory-matrix.md    — the 50 factories + 10 businesses with mechanics, inputs and completion status
 *   docs/dependency-graph.md  — per-chapter mermaid flowcharts (item → building → item) and a full item table
 * Run: npx tsx tools/gen-content-docs.ts
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FULL_CATALOG } from '../src/content/catalog';
import statusJson from '../src/content/status.json';
import type { BuildingDef, RecipeDef } from '../src/content/types';
import { validateContent } from '../src/content/validate';
import enJson from '../src/i18n/en/content.json';

interface Status {
  data: boolean;
  simMechanics: string;
  interiorPlayable: boolean;
  art: string;
  audio: string;
  saveTested: boolean;
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const en = enJson as Record<string, string>;
const status = statusJson as Record<string, Status>;
const items = FULL_CATALOG.flatMap((p) => p.items);
const recipes = FULL_CATALOG.flatMap((p) => p.recipes);
const machines = new Map(FULL_CATALOG.flatMap((p) => p.machines).map((m) => [m.id, m]));
const buildings = FULL_CATALOG.flatMap((p) => p.buildings);
const sources = FULL_CATALOG.flatMap((p) => p.sources);
const unlocks = new Map(FULL_CATALOG.flatMap((p) => p.unlocks).map((u) => [u.id, u]));
const demand = new Set(FULL_CATALOG.flatMap((p) => p.demand).map((d) => d.item));

const name = (kind: string, id: string): string => en[`${kind}.${id}`] ?? id;
const recipesOf = (b: BuildingDef): RecipeDef[] => recipes.filter((r) => b.machines.includes(r.machine));
const hostOf = (r: RecipeDef): BuildingDef | undefined => buildings.find((b) => b.machines.includes(r.machine));
const md = (s: string): string => s.replace(/\|/g, '\\|');
const yesNo = (v: boolean): string => (v ? 'yes' : 'no');

function externalInputs(b: BuildingDef): string[] {
  const rs = recipesOf(b);
  const made = new Set(rs.flatMap((r) => r.outputs.map((o) => o.item)));
  return [...new Set(rs.flatMap((r) => r.inputs.map((i) => i.item)))].filter((i) => !made.has(i));
}
function outputsOf(b: BuildingDef): string[] {
  return [...new Set(recipesOf(b).flatMap((r) => r.outputs.map((o) => o.item)))];
}
function suppliersOf(itemId: string, except?: string): string[] {
  const out = new Set<string>();
  for (const r of recipes) {
    if (!r.outputs.some((o) => o.item === itemId)) continue;
    const h = hostOf(r);
    if (h && h.id !== except) out.add(name('building', h.id));
  }
  for (const s of sources) {
    if (s.item !== itemId) continue;
    out.add(s.kind === 'import' ? 'import' : s.building ? name('building', s.building) : s.kind);
  }
  return [...out];
}

// ───────────── factory matrix ─────────────
const counted = buildings
  .filter((b) => b.kind === 'factory' || b.kind === 'business')
  .sort((a, b) => (a.kind === b.kind ? (a.factoryIndex ?? a.businessIndex ?? 0) - (b.factoryIndex ?? b.businessIndex ?? 0) : a.kind === 'factory' ? -1 : 1));

const { errors, warnings, stats } = validateContent(FULL_CATALOG);
const header = '| # | id | Name | Ch | Levels | Signature machines | Recipes | Mechanics | Inputs sourced from | Data | Sim | Interior | Art | Audio | Save |';
const sep = '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|';
const row = (b: BuildingDef): string => {
  const st = status[b.id];
  const sig = b.machines.filter((m) => !machines.get(m)?.role).map((m) => name('machine', m));
  const inputs = externalInputs(b)
    .map((i) => `${name('item', i)} ← ${suppliersOf(i, b.id).join(' / ') || '—'}`)
    .join('; ');
  const idx = b.kind === 'factory' ? String(b.factoryIndex).padStart(2, '0') : `B${b.businessIndex}`;
  return `| ${idx} | \`${b.id}\` | ${md(name('building', b.id))} | ${b.chapter} | ${b.levels.length} | ${md(sig.join(', ') || '—')} | ${recipesOf(b).length} | ${b.mechanics.join(', ')} | ${md(inputs || (b.sells ? `sells ${b.sells.length} items` : '—'))} | ${st ? yesNo(st.data) : '?'} | ${st?.simMechanics ?? '?'} | ${st ? yesNo(st.interiorPlayable) : '?'} | ${st?.art ?? '?'} | ${st?.audio ?? '?'} | ${st ? yesNo(st.saveTested) : '?'} |`;
};

const hooks: [string, string][] = [];
for (const it of FULL_CATALOG[0].items) {
  if (!sources.some((s) => s.item === it.id && s.kind === 'import')) continue;
  const rs = recipes.filter((r) => r.outputs.some((o) => o.item === it.id));
  if (rs.length) hooks.push([it.id, rs.map((r) => `\`${r.id}\` @ ${name('building', hostOf(r)?.id ?? '?')}`).join(', ')]);
}

const matrix = [
  '# Factory & business matrix',
  '',
  '_Generated by `npx tsx tools/gen-content-docs.ts` from `src/content/catalog.ts` and `src/content/status.json`. Do not edit by hand._',
  '',
  `Catalog: ${stats.items} items · ${stats.recipes} recipes · ${stats.factories} factories · ${stats.businesses} businesses · ${stats.machines} machines · ${stats.sources} sources · ${stats.unlocks} unlocks. Validator: ${errors.length} errors, ${warnings.length} warnings.`,
  '',
  'Status columns come from `status.json` and are maintained by the integration owner: **Data** = catalog entry exists; **Sim** = simulation mechanics (none/partial/done); **Interior** = interior playable; **Art** / **Audio** = asset state; **Save** = save/load tested.',
  '',
  '## Manufacturing (50)',
  '',
  header,
  sep,
  ...counted.filter((b) => b.kind === 'factory').map(row),
  '',
  '## Businesses (10)',
  '',
  header,
  sep,
  ...counted.filter((b) => b.kind === 'business').map(row),
  '',
  '## Backward integration into chapter 1',
  '',
  'Chapter-1 parts start as imports; these recipes let the player replace each import with internal supply.',
  '',
  '| Chapter-1 import | Internal recipe(s) |',
  '|---|---|',
  ...hooks.map(([i, r]) => `| \`${i}\` (${name('item', i)}) | ${r} |`),
  '',
  '## Identities',
  '',
  ...counted.map((b) => `- **${md(name('building', b.id))}** (\`${b.id}\`): ${b.identity}`),
  '',
];

// ───────────── dependency graph ─────────────
const mid = (prefix: string, id: string): string => `${prefix}_${id}`;
const label = (s: string): string => s.replace(/"/g, "'");
const chapterOfItem = new Map<string, number>();
for (const it of items) {
  let ch = 99;
  for (const s of sources.filter((x) => x.item === it.id)) ch = Math.min(ch, s.unlock ? (unlocks.get(s.unlock)?.chapter ?? 99) : 1);
  for (const r of recipes.filter((x) => x.outputs.some((o) => o.item === it.id))) ch = Math.min(ch, hostOf(r)?.chapter ?? 99);
  chapterOfItem.set(it.id, ch);
}

const graph: string[] = [
  '# Content dependency graph',
  '',
  '_Generated by `npx tsx tools/gen-content-docs.ts`. Do not edit by hand._',
  '',
  'Per-chapter flowcharts show, for every building of that chapter with recipes, the items it takes in from outside and the items it makes (item → building → item). Items with an import source are drawn with a dashed border.',
  '',
];
const imported = new Set(sources.filter((s) => s.kind === 'import').map((s) => s.item));
for (let ch = 1; ch <= 7; ch++) {
  const bs = buildings.filter((b) => b.chapter === ch && recipesOf(b).length > 0);
  if (!bs.length) continue;
  const lines = ['```mermaid', 'flowchart LR', '  classDef imp stroke-dasharray: 4 3', '  classDef bld fill:#f3e7c9,stroke:#8a6d3b'];
  const itemNodes = new Set<string>();
  for (const b of bs) {
    lines.push(`  ${mid('b', b.id)}["${label(name('building', b.id))}"]:::bld`);
    for (const i of externalInputs(b)) {
      itemNodes.add(i);
      lines.push(`  ${mid('i', i)} --> ${mid('b', b.id)}`);
    }
    for (const o of outputsOf(b)) {
      itemNodes.add(o);
      lines.push(`  ${mid('b', b.id)} --> ${mid('i', o)}`);
    }
  }
  for (const i of itemNodes) lines.push(`  ${mid('i', i)}(["${label(name('item', i))}"])${imported.has(i) ? ':::imp' : ''}`);
  lines.push('```');
  graph.push(`## Chapter ${ch}`, '', ...lines, '');
}

graph.push('## Item table', '', '| Item | Name | Category | First ch | Producers (recipe @ building) | Consumers | Sources |', '|---|---|---|---|---|---|---|');
for (const it of items) {
  const prod = recipes.filter((r) => r.outputs.some((o) => o.item === it.id)).map((r) => `${r.id} @ ${hostOf(r)?.id ?? '?'}`);
  const cons = [
    ...recipes.filter((r) => r.inputs.some((i) => i.item === it.id)).map((r) => r.id),
    ...buildings.filter((b) => b.sells?.includes(it.id)).map((b) => `sold by ${b.id}`),
    ...buildings.filter((b) => b.consumes?.includes(it.id)).map((b) => `used by ${b.id}`),
    ...(demand.has(it.id) ? ['resident demand'] : []),
  ];
  const src = sources.filter((s) => s.item === it.id).map((s) => `${s.kind} ${s.unitPrice}¢${s.building ? ` (${s.building})` : ''}`);
  graph.push(`| \`${it.id}\` | ${md(name('item', it.id))} | ${it.category} | ${chapterOfItem.get(it.id) ?? '?'} | ${prod.join(', ') || '—'} | ${cons.join(', ') || (it.category === 'service' ? 'service output' : '—')} | ${src.join(', ') || '—'} |`);
}
graph.push('');

mkdirSync(resolve(root, 'docs'), { recursive: true });
writeFileSync(resolve(root, 'docs/factory-matrix.md'), matrix.join('\n'));
writeFileSync(resolve(root, 'docs/dependency-graph.md'), graph.join('\n'));
console.log(`wrote docs/factory-matrix.md (${counted.length} rows) and docs/dependency-graph.md (${items.length} items)`);
